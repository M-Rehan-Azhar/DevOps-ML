"""Generate frontend/src/app/feature-schema.ts from the packaged model bundle.

Run from the project root after package_existing.py and make_payload.py:
    python backend\\export_frontend_schema.py

Keeps the Angular form fields, dropdown options and numeric ranges identical
to the schema the Flask API validates against.
"""

from pathlib import Path
import json

import joblib

ROOT = Path(__file__).resolve().parent.parent
bundle = joblib.load(ROOT / "backend/models/model_bundle.joblib")
payload = json.loads((ROOT / "backend/test_payload.json").read_text(encoding="utf-8"))
features, schema = bundle["features"], bundle["schema"]

LABELS = {
    "hour_of_day": "Hour of day",
    "day_of_week": "Day of week (0-6)",
    "is_weekend": "Is weekend (0 = no, 1 = yes)",
    "verified": "Verified account (0 = no, 1 = yes)",
    "account_age_days": "Account age (days)",
    "content_length": "Content length (characters)",
    "num_hashtags": "Number of hashtags",
}


def label(name):
    return LABELS.get(name, name.replace("_", " ").capitalize())


lines = [
    "// Generated by backend/export_frontend_schema.py from model_bundle.joblib.",
    "// Raw model inputs in training order; follower_growth_rate is derived",
    "// server-side as followers / (account_age_days + 1).",
    "export type Feature = {",
    "  name: string;",
    "  label: string;",
    "  kind: 'number' | 'category';",
    "  required: boolean;",
    "  options?: string[];",
    "  min?: number;",
    "  max?: number;",
    "};",
    "",
    "export const FEATURES: Feature[] = [",
]
for name in features:
    rule = schema[name]
    entry = {"name": name, "label": label(name), "kind": rule["kind"], "required": True}
    if rule["kind"] == "category":
        entry["options"] = rule["options"]
    else:
        entry["min"], entry["max"] = rule["min"], rule["max"]
    lines.append(f"  {json.dumps(entry)},")
sample = {k: (str(v) if schema[k]["kind"] == "category" else v) for k, v in payload.items()}
lines += [
    "];",
    "",
    "// Non-sensitive sample record (same values as backend/test_payload.json).",
    f"export const SAMPLE_RECORD: Record<string, string | number> = {json.dumps(sample, indent=2)};",
    "",
]
out = ROOT / "frontend/src/app/feature-schema.ts"
out.write_text("\n".join(lines), encoding="utf-8")
print(f"Wrote {out.relative_to(ROOT)} with {len(features)} fields")
